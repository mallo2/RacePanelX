export type JTSize = 'small' | 'large';
export type JTColor = readonly [number, number, number];
export type Pixel = JTColor;

const SIZE_PARAMS = {
  small: {
    glyphs: GLYPHS_SMALL,
    charWidth: 6,
    charHeight: 8,
    charGap: 1,
    bits: 6,
  },
  large: {
    glyphs: GLYPHS_LARGE,
    charWidth: 10,
    charHeight: 14,
    charGap: 1,
    bits: 10,
  },
} as const;

const PANEL_W = 96;
const PANEL_H = 16;

const CUSTOM_WIDTHS: Record<string, readonly [number, number]> = {
  'large::': [4, 4],
  'large:,': [4, 4],
};

const COLORS: Record<string, JTColor> = {
  red: [255, 0, 0],
  green: [0, 255, 0],
  blue: [0, 0, 255],
  magenta: [255, 0, 255],
  yellow: [255, 255, 0],
  cyan: [0, 255, 255],
  white: [255, 255, 255],
};

export interface JTDocument {
  data: {
    graffitiData: number[];
    graffitiType: number;
    mode: number;
    pixelHeight: number;
    pixelWidth: number;
    speed: number;
  };
  dataType: number;
}

class JTImageGenerator {
  generateJTImage(text: string, size: JTSize = 'small', color: keyof typeof COLORS = 'red'): number[] {
    const selectedColor = COLORS[color] || COLORS.red;
    const pixels = this.textToPixels(text.toUpperCase(), selectedColor, size);
    return this.pixelsToGraffiti(pixels);
  }

  private textToPixels(text: string, color: JTColor, size: JTSize): Pixel[][] {
    const startX = size === 'small' ? 3 : 5;
    const startY = size === 'small' ? 5 : 2;

    const p = SIZE_PARAMS[size];
    const glyphs = p.glyphs;
    const charWidth = p.charWidth;
    const charGap = p.charGap;
    const bits = p.bits;

    const pixels: Pixel[][] = Array.from({ length: PANEL_H }, () =>
      Array.from({ length: PANEL_W }, () => [0, 0, 0] as JTColor)
    );

    let cx = startX;

    for (const ch of text) {
      if (!(ch in glyphs)) {
        console.warn(`Avertissement : '${ch}' non supporté, ignoré.`);
        continue;
      }

      let chBits: number;
      let currentWidth: number;

      const customKey = `${size}:${ch}`;
      if (customKey in CUSTOM_WIDTHS) {
        [chBits, currentWidth] = CUSTOM_WIDTHS[customKey];
      } else {
        [chBits, currentWidth] = [bits, charWidth];
      }

      const glyph = (glyphs as Record<string, number[]>)[ch];
      for (let rowIdx = 0; rowIdx < glyph.length; rowIdx++) {
        const byte = glyph[rowIdx];
        for (let bit = chBits - 1; bit >= 0; bit--) {
          const col = cx + (chBits - 1 - bit);
          const r = startY + rowIdx;
          if (col >= 0 && col < PANEL_W && r >= 0 && r < PANEL_H) {
            if ((byte >> bit) & 1) {
              pixels[r][col] = color;
            }
          }
        }
      }
      cx += currentWidth + charGap;
      if (cx >= PANEL_W) break;
    }

    return pixels;
  }

  private pixelsToGraffiti(pixels: Pixel[][]): number[] {
    const rPlane = new Array(192).fill(0);
    const gPlane = new Array(192).fill(0);
    const bPlane = new Array(192).fill(0);

    for (let col = 0; col < PANEL_W; col++) {
      for (let row = 0; row < PANEL_H; row++) {
        const [pr, pg, pb] = pixels[row][col];
        const byteIdx = col * 2 + Math.floor(row / 8);
        const bitIdx = 7 - (row % 8);

        if (pr) rPlane[byteIdx] |= (1 << bitIdx);
        if (pg) gPlane[byteIdx] |= (1 << bitIdx);
        if (pb) bPlane[byteIdx] |= (1 << bitIdx);
      }
    }

    return [...rPlane, ...gPlane, ...bPlane];
  }


}

export default new JTImageGenerator();
